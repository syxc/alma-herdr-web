"""Build and check complete Unicode-page subsets of the pinned icon font."""

import argparse
import hashlib
from collections import defaultdict
from pathlib import Path

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
DIRECTORY = ROOT / "web/vendor/nerd-fonts"
SOURCE = DIRECTORY / "symbols-nerd-font-mono.woff2"
SOURCE_SHA256 = "3a4676f08bf19e70867bc5eb2e9a394fc9c630fab9ebbb4cccbb15d67601e7c0"
CSS = DIRECTORY / "symbols.css"
MANIFEST = ROOT / "web/src/icon-font-ranges.ts"


def ranges(points):
    result = []
    for point in sorted(points):
        if result and result[-1][1] == point - 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def unicode_range(points):
    return ", ".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in ranges(points)
    )


def outline(glyphs, name):
    pen = DecomposingRecordingPen(glyphs)
    glyphs[name].draw(pen)
    return pen.value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing files")
    args = parser.parse_args()
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest() == SOURCE_SHA256, "Source font changed"
    original = TTFont(SOURCE, recalcTimestamp=False)
    cmap = original.getBestCmap()
    assert len(cmap) == 10397, "Unexpected source character count"
    pages = defaultdict(set)
    for point in cmap:
        pages[point // 256].add(point)

    css = ["/* Generated by scripts/subset-icon-font.py. */\n"]
    manifest = [
        "// Generated by scripts/subset-icon-font.py.\n",
        "export const iconFontChunks = [\n",
    ]
    seen = {}
    total_bytes = 0
    original_glyphs = original.getGlyphSet()
    for page, points in sorted(pages.items()):
        filename = f"symbols-{page:03x}.woff2"
        path = DIRECTORY / filename
        if not args.check:
            part = TTFont(SOURCE, recalcTimestamp=False)
            options = subset.Options()
            options.glyph_names = True
            options.drop_tables += ["FFTM"]
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=points)
            worker.subset(part)
            part.save(path)
            part.close()
        part = TTFont(path)
        part_cmap = part.getBestCmap()
        assert set(part_cmap) == points, filename + ": character coverage changed"
        assert not seen.keys() & part_cmap.keys(), filename + ": duplicate mapping"
        seen.update(part_cmap)
        glyphs = part.getGlyphSet()
        for point, name in part_cmap.items():
            source_name = cmap[point]
            assert part["hmtx"][name] == original["hmtx"][source_name], f"U+{point:X}: metrics changed"
            assert outline(glyphs, name) == outline(original_glyphs, source_name), f"U+{point:X}: outline changed"
        for table, fields in {
            "head": ["unitsPerEm"],
            "hhea": ["ascent", "descent", "lineGap"],
            "OS/2": ["sTypoAscender", "sTypoDescender", "sTypoLineGap", "usWinAscent", "usWinDescent"],
        }.items():
            for field in fields:
                assert getattr(part[table], field) == getattr(original[table], field), (filename, table, field)
        total_bytes += path.stat().st_size
        css.append(
            '@font-face {\n  font-family: "Symbols Nerd Font Mono";\n'
            f'  src: url("{filename}") format("woff2");\n'
            '  font-style: normal;\n  font-weight: 400;\n  font-display: swap;\n'
            f'  unicode-range: {unicode_range(points)};\n}}\n'
        )
        pairs = ", ".join(f"[0x{start:x}, 0x{end:x}]" for start, end in ranges(points))
        manifest.append(f"  {{ file: '{filename}', ranges: [{pairs}] }},\n")
        part.close()
    manifest.append(
        "] as const satisfies readonly { file: string; ranges: readonly (readonly [number, number])[] }[];\n"
    )
    assert seen.keys() == cmap.keys(), "Incomplete character coverage"
    for path, content in [(CSS, "\n".join(css)), (MANIFEST, "".join(manifest))]:
        if args.check:
            assert path.read_text() == content, str(path.relative_to(ROOT)) + ": stale manifest"
        else:
            path.write_text(content)
    expected = {f"symbols-{page:03x}.woff2" for page in pages}
    actual = {path.name for path in DIRECTORY.glob("symbols-*.woff2") if path != SOURCE}
    assert actual == expected, "Unexpected or missing font chunks"
    print(f"Checked {len(seen):,} characters in {len(pages)} chunks: cmap, horizontal metrics, outlines, vertical metrics and CSS/Canvas ranges match.")
    print(f"Source: {SOURCE.stat().st_size:,} bytes; chunks: {total_bytes:,} bytes; largest: {max((DIRECTORY / name).stat().st_size for name in expected):,} bytes.")


if __name__ == "__main__":
    main()
